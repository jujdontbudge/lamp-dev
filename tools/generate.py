#!/usr/bin/env python3
"""Deterministic stdlib-only public codegen. schema.json is the input, never the spec."""
import argparse
import copy
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def pascal(value):
    return ''.join(x[:1].upper() + x[1:] for x in re.split(r'[_\- .]+', value))


def generate():
    schema = json.loads((ROOT / 'contracts/public/schema.json').read_text())
    defs = copy.deepcopy(schema['$defs'])
    # Lift inline enums/objects into named types, preserving wire names.
    def lift(s, name, top=False):
        if '$ref' in s:
            return
        if s.get('type') == 'array':
            lift(s['items'], name + 'Item')
        if s.get('type') == 'object' and 'properties' in s:
            for k, v in s['properties'].items():
                lift(v, name + pascal(k))
        for key in ('oneOf', 'anyOf'):
            for i, v in enumerate(s.get(key, [])):
                lift(v, name + 'Variant' + str(i))
        if not top and ('enum' in s or isinstance(s.get('const'), str) or ('properties' in s and s.get('type') == 'object')):
            defs[name] = copy.deepcopy(s)
            s.clear()
            s['$ref'] = '#/$defs/' + name
    for name in list(defs):
        lift(defs[name], name, True)

    def typ(s, lang):
        if '$ref' in s:
            return s['$ref'].rsplit('/', 1)[1]
        t = s.get('type')
        if t == 'string': return 'string' if lang == 'go' else 'String'
        if t == 'boolean': return 'bool'
        if t == 'integer': return ('int64' if lang == 'go' else 'i64') if s.get('minimum', 0) < 0 else ('uint64' if lang == 'go' else 'u64')
        if t == 'array': return ('[]' + typ(s['items'], lang)) if lang == 'go' else ('Vec<' + typ(s['items'], lang) + '>')
        if t == 'object' and isinstance(s.get('additionalProperties'), dict):
            return ('map[string]' + typ(s['additionalProperties'], lang)) if lang == 'go' else ('std::collections::BTreeMap<String, ' + typ(s['additionalProperties'], lang) + '>')
        return 'json.RawMessage' if lang == 'go' else 'serde_json::Value'

    go = ['// Code generated by tools/generate.py. DO NOT EDIT.', 'package api', 'import "encoding/json"']
    rust = ['// Code generated by tools/generate.py. DO NOT EDIT.', 'use serde::{Deserialize, Serialize};']
    for name, s in sorted(defs.items()):
        values = s.get('enum', [s['const']] if isinstance(s.get('const'), str) else None)
        if values:
            go += [f'type {name} string', 'const ('] + [f'{name}{pascal(v)} {name} = {json.dumps(v)}' for v in values] + [')']
            rust += ['#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]', f'pub enum {name} {{']
            for v in values: rust += [f'#[serde(rename = {json.dumps(v)})]', f'{pascal(v)},']
            rust += ['}']
        elif s.get('type') == 'object' and 'properties' in s:
            required = set(s.get('required', []))
            go += [f'type {name} struct {{']
            rust += ['#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]', '#[serde(deny_unknown_fields)]', f'pub struct {name} {{']
            for k, v in s['properties'].items():
                gt, rt = typ(v, 'go'), typ(v, 'rust')
                optional = k not in required
                # Pointer to slice/map preserves absent vs supplied-empty selectors.
                if optional: gt = '*' + gt; rt = 'Option<' + rt + '>'
                go += [f'{pascal(k)} {gt} `json:"{k}{",omitempty" if optional else ""}"`']
                rust += [f'#[serde(rename = "{k}"{", default, skip_serializing_if = \"Option::is_none\"" if optional else ""})]']
                rust += [f'pub {"r#" if k in ["type", "ref"] else ""}{k}: {rt},']
            go += ['}']; rust += ['}']
        elif 'oneOf' in s or 'anyOf' in s:
            variants = s.get('oneOf', s.get('anyOf'))
            # Go retains raw tagged JSON; admission validates oneOf and exact shape.
            go += [f'type {name} = json.RawMessage']
            rust += ['#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]', '#[serde(untagged)]', f'pub enum {name} {{']
            rust += [f'Variant{i}({typ(v, "rust")}), ' for i, v in enumerate(variants)] + ['}']
        else:
            go += [f'type {name} = {typ(s, "go")}']
            rust += [f'pub type {name} = {typ(s, "rust")};']
    meta = schema['x-lamp-operations']
    go += ['type OperationDescriptor struct { Name, Scope, CLI, Method, Path, InputSchema, ResultSchema, Authorization string; Mutation bool }', 'var Operations = []OperationDescriptor{']
    rust += ['#[derive(Debug, Clone, Copy)]', 'pub struct OperationDescriptor { pub name: &\'static str, pub scope: &\'static str, pub cli: &\'static str, pub method: &\'static str, pub path: &\'static str, pub input_schema: &\'static str, pub result_schema: &\'static str, pub authorization: &\'static str, pub mutation: bool }', 'pub const OPERATIONS: &[OperationDescriptor] = &[']
    fields = ['name','scope','cli','method','path','input_schema','result_schema','authorization']
    for n, o in sorted(meta.items()):
        vals = [n] + [o[k] for k in fields[1:]]
        go += ['{' + ','.join(json.dumps(v) for v in vals) + ',' + str(o['mutation']).lower() + '},']
        rust += ['OperationDescriptor { ' + ', '.join(k + ': ' + json.dumps(v) for k,v in zip(fields, vals)) + ', mutation: ' + str(o['mutation']).lower() + ' },']
    go += ['}']; rust += ['];']
    for n, v in sorted(schema['x-lamp-limits'].items()):
        go += [f'const {pascal(n)} = {v}'];rust += [f'pub const {n.upper()}: usize = {v};']
    outputs = {'pkg/api/generated.go':'\n'.join(go)+'\n', 'crates/lamp-contracts/src/generated.rs':'\n'.join(rust)+'\n'}
    # OpenAPI 3.1 uses exactly the same component schemas and operation dictionary.
    def refs(v):
        if isinstance(v, dict): return {k:(x.replace('#/$defs/', '#/components/schemas/') if k=='$ref' else refs(x)) for k,x in v.items()}
        if isinstance(v, list): return [refs(x) for x in v]
        return v
    openapi = {'openapi':'3.1.0','info':{'title':'Lamp API','version':'1.0.0'},'paths':{},'components':{'schemas':refs(schema['$defs'])}}
    for n,o in sorted(meta.items()):
        inp=copy.deepcopy(schema['$defs'][o['input_schema']]); pp=inp['properties']; req=inp.get('required',[]); parameters=[]
        for k in list(pp):
            loc = 'path' if '{'+k+'}' in o['path'] else 'header' if k in ['idempotency_key','expected_revision'] else 'query' if o['method']=='get' else None
            if loc:
                wire = {'idempotency_key':'Idempotency-Key','expected_revision':'If-Match'}.get(k,k)
                parameters.append({'name':wire,'in':loc,'required':k in req,'schema':refs(pp.pop(k))})
                if k in req: req.remove(k)
        body={'operationId':n,'x-lamp-scope':o['scope'],'x-lamp-authorization':o['authorization'],'parameters':parameters,'responses':{'202' if o['mutation'] else '200':{'description':'Accepted Operation' if o['mutation'] else 'Result','content':{'application/json':{'schema':{'$ref':'#/components/schemas/'+o['result_schema']}}}}}}
        for status in sorted(set(schema['x-lamp-errors'].values())):body['responses'][str(status)]={'description':'Lamp error','content':{'application/json':{'schema':{'$ref':'#/components/schemas/ErrorEnvelope'}}}}
        if o['method']!='get': body['requestBody']={'required':True,'content':{'application/json':{'schema':refs(inp)}}}
        if n=='event_list':body['responses']['200']['content']['text/event-stream']={'schema':{'type':'string'}}
        if n in ['blob_download','artifact_download']:body['responses']['200']['content']['application/octet-stream']={'schema':{'type':'string','format':'binary'}}
        if n=='blob_upload':body['requestBody']={'required':True,'content':{'application/octet-stream':{'schema':{'type':'string','format':'binary'}}}};body['parameters'].append({'name':'Content-Range','in':'header','required':True,'schema':{'type':'string'}})
        assert o['method'] not in openapi['paths'].setdefault(o['path'],{}), n
        openapi['paths'][o['path']][o['method']]=body
    outputs['contracts/public/openapi.json']=json.dumps(openapi,indent=2)+'\n'
    return outputs


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    outputs=generate()
    # Format in temporary files so --check never mutates checked-in output.
    import tempfile
    with tempfile.TemporaryDirectory() as tmp:
        for path, data in outputs.items():
            p=Path(tmp)/Path(path).name;p.write_text(data)
            if path.endswith('.go'):subprocess.run(['gofmt','-w',str(p)],check=True)
            if path.endswith('.rs'):subprocess.run(['rustfmt','--edition','2024',str(p)],check=True)
            data=p.read_bytes();target=ROOT/path
            if args.check:
                if not target.exists() or target.read_bytes()!=data:raise SystemExit('stale generated file: '+path)
            else:target.write_bytes(data)
    print('public codegen: clean' if args.check else 'public codegen: generated')

if __name__=='__main__':main()
