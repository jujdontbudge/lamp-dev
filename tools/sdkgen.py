#!/usr/bin/env python3
"""Generate the TypeScript SDK from contracts/public/schema.json.

Stdlib only and deterministic. Every canonical operation becomes one client
method using the same path, header and query mapping as the CLI and OpenAPI
(idempotency_key -> Idempotency-Key, expected_revision -> If-Match, GET inputs
-> query, other inputs -> JSON body). Mutations get an idempotency key when the
caller gives none, and clients can wait for the resulting Operation.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VERSION = '0.1.0'
HEADER = 'Code generated by tools/sdkgen.py from contracts/public/schema.json. DO NOT EDIT.'


def camel(name):
    head, *rest = name.split('_')
    return head + ''.join(p[:1].upper() + p[1:] for p in rest)


def ts_type(s):
    if not isinstance(s, dict) or not s:
        return 'unknown'
    if '$ref' in s:
        return s['$ref'].rsplit('/', 1)[1]
    if 'enum' in s:
        return ' | '.join(json.dumps(v) for v in s['enum'])
    if 'const' in s:
        return json.dumps(s['const'])
    for key in ('oneOf', 'anyOf'):
        if key in s:
            return '(' + ' | '.join(ts_type(v) for v in s[key]) + ')'
    t = s.get('type')
    if isinstance(t, list):
        return ' | '.join(ts_type({**s, 'type': x}) for x in t)
    if t == 'string':
        return 'string'
    if t in ('integer', 'number'):
        return 'number'
    if t == 'boolean':
        return 'boolean'
    if t == 'null':
        return 'null'
    if t == 'array':
        return 'Array<' + ts_type(s.get('items', {})) + '>'
    if t == 'object':
        if 'properties' in s:
            req = set(s.get('required', []))
            fields = [f'{json.dumps(k)}{"" if k in req else "?"}: {ts_type(v)}' for k, v in s['properties'].items()]
            return '{ ' + '; '.join(fields) + ' }'
        if isinstance(s.get('additionalProperties'), dict):
            return 'Record<string, ' + ts_type(s['additionalProperties']) + '>'
        return 'Record<string, unknown>'
    return 'unknown'


def operations(schema):
    ops = []
    for name, o in sorted(schema['x-lamp-operations'].items()):
        ops.append({'name': name, 'method': o['method'].upper(), 'path': o['path'], 'mutation': o['mutation'],
                    'input': o['input_schema'], 'result': o['result_schema'], 'scope': o['scope'], 'cli': o['cli']})
    return ops


def gen_typescript(schema, ops):
    defs = schema['$defs']
    dts = [f'// {HEADER}', '']
    for name in sorted(defs):
        s = defs[name]
        if s.get('type') == 'object' and 'properties' in s:
            req = set(s.get('required', []))
            dts.append(f'export interface {name} {{')
            for k, v in s['properties'].items():
                ro = 'readonly ' if v.get('readOnly') else ''
                dts.append(f'  {ro}{json.dumps(k)}{"" if k in req else "?"}: {ts_type(v)};')
            dts.append('}')
        else:
            dts.append(f'export type {name} = {ts_type(s)};')
    dts += ['', 'export interface ClientOptions {',
            '  /** Local Unix socket of lampd (Node only). */', '  socket?: string;',
            '  /** HTTPS API origin, for example a gateway. */', '  baseUrl?: string;',
            '  /** Bearer credential; never put it in a URL. */', '  token?: string;', '}', '',
            'export interface OperationDescriptor { name: string; method: string; path: string; mutation: boolean; inputSchema: string; resultSchema: string; scope: string; cli: string; }',
            'export declare const OPERATIONS: Record<string, OperationDescriptor>;',
            'export declare const SDK_VERSION: string;',
            'export declare class LampError extends Error { status: number; code: string; retryable: boolean; details: unknown; requestId?: string; }', '',
            'export declare class LampClient {', '  constructor(options?: ClientOptions);',
            '  /** Call any canonical operation by name. */',
            '  call(name: string, input?: Record<string, unknown>): Promise<any>;',
            '  /** Wait until an Operation leaves accepted/running, returning it. */',
            '  waitOperation(operationId: string, timeoutMs?: number): Promise<Operation>;']
    for o in ops:
        dts.append(f'  /** `{o["cli"]}` — {o["method"]} {o["path"]} (scope {o["scope"]}) */')
        dts.append(f'  {camel(o["name"])}(input: {o["input"]}): Promise<{o["result"]}>;')
    dts += ['}', '']

    table = {o['name']: {'name': o['name'], 'method': o['method'], 'path': o['path'], 'mutation': o['mutation'],
                         'inputSchema': o['input'], 'resultSchema': o['result'], 'scope': o['scope'], 'cli': o['cli']} for o in ops}
    js = [f'// {HEADER}', f'export const SDK_VERSION = {json.dumps(VERSION)};',
          'export const OPERATIONS = ' + json.dumps(table, indent=1, sort_keys=True) + ';', '', RUNTIME_JS, '']
    js.append('for (const name of Object.keys(OPERATIONS)) {')
    js.append('  const method = name.replace(/_([a-z])/g, (_, c) => c.toUpperCase());')
    js.append('  LampClient.prototype[method] = function (input) { return this.call(name, input); };')
    js.append('}')
    pkg = {'name': '@eilmer/lamp-sdk', 'version': VERSION, 'description': 'Lamp API client generated from the canonical schema',
           'license': 'Apache-2.0', 'type': 'module', 'main': 'index.js', 'types': 'index.d.ts',
           'files': ['index.js', 'index.d.ts', 'README.md', 'LICENSE'], 'engines': {'node': '>=18'},
           'repository': {'type': 'git', 'url': 'git+https://github.com/JohanSardar/lamp.git', 'directory': 'sdk/typescript'},
           'homepage': 'https://github.com/JohanSardar/lamp'}
    readme = ('# Lamp TypeScript SDK\n\nGenerated from `contracts/public/schema.json`; do not edit.\n\n'
              '```js\nimport { LampClient } from "@eilmer/lamp-sdk";\n'
              'const lamp = new LampClient({ socket: process.env.LAMP_SOCKET, token: process.env.LAMP_TOKEN });\n'
              'const accepted = await lamp.blobCreate({ size_bytes: 3, media_type: "text/plain" });\n'
              'const op = await lamp.waitOperation(accepted.operation_id);\n```\n\n'
              'Every method maps to one canonical operation (`OPERATIONS`). Errors throw `LampError` with the Lamp error code.\n')
    return {'sdk/typescript/index.d.ts': '\n'.join(dts), 'sdk/typescript/index.js': '\n'.join(js) + '\n',
            'sdk/typescript/package.json': json.dumps(pkg, indent=2) + '\n', 'sdk/typescript/README.md': readme}


RUNTIME_JS = r'''export class LampError extends Error {
  constructor(status, body) {
    const e = (body && body.error) || {};
    super(e.message || `HTTP ${status}`);
    this.name = "LampError";
    this.status = status;
    this.code = e.code || "UNKNOWN";
    this.retryable = !!e.retryable;
    this.details = e.details;
    this.requestId = body && body.request_id;
  }
}

function randomKey() {
  const b = new Uint8Array(32);
  globalThis.crypto.getRandomValues(b);
  return "sdk-" + Array.from(b, (x) => x.toString(16).padStart(2, "0")).join("");
}

export class LampClient {
  constructor(options = {}) {
    this.socket = options.socket;
    this.baseUrl = options.baseUrl;
    this.token = options.token;
    if (!this.socket && !this.baseUrl) throw new Error("LampClient needs socket or baseUrl");
    if (this.baseUrl && this.token && !this.baseUrl.startsWith("https://")) throw new Error("credentialed remote URLs must be HTTPS");
  }

  request(op, input) {
    const body = { ...(input || {}) };
    const headers = { accept: "application/json" };
    let path = op.path;
    for (const k of Object.keys(body)) {
      const ph = "{" + k + "}";
      if (path.includes(ph)) {
        const v = body[k];
        if (typeof v !== "string" || !v || /[/\0]/.test(v)) throw new Error("invalid path selector " + k);
        path = path.replace(ph, encodeURIComponent(v));
        delete body[k];
      }
    }
    if (path.includes("{")) throw new Error("missing resource ID for " + op.name);
    if (op.mutation) {
      if (body.idempotency_key === undefined) body.idempotency_key = randomKey();
      headers["Idempotency-Key"] = String(body.idempotency_key);
      delete body.idempotency_key;
      if (body.expected_revision !== undefined) {
        headers["If-Match"] = String(body.expected_revision);
        delete body.expected_revision;
      }
    }
    let data;
    if (op.method === "GET") {
      const q = new URLSearchParams();
      for (const [k, v] of Object.entries(body)) q.set(k, typeof v === "object" ? JSON.stringify(v) : String(v));
      const s = q.toString();
      if (s) path += "?" + s;
    } else {
      data = JSON.stringify(body);
      headers["content-type"] = "application/json";
    }
    if (this.token) headers.authorization = "Bearer " + this.token;
    return { method: op.method, path, headers, data };
  }

  async send({ method, path, headers, data }) {
    if (this.baseUrl) {
      const res = await fetch(new URL(path, this.baseUrl), { method, headers, body: data, redirect: "error" });
      return { status: res.status, text: await res.text() };
    }
    const http = await import("node:http");
    return await new Promise((resolve, reject) => {
      const req = http.request({ socketPath: this.socket, method, path, headers: { ...headers, host: "lamp" } }, (res) => {
        let text = "";
        res.setEncoding("utf8");
        res.on("data", (c) => (text += c));
        res.on("end", () => resolve({ status: res.statusCode, text }));
      });
      req.on("error", reject);
      if (data !== undefined) req.write(data);
      req.end();
    });
  }

  async call(name, input) {
    const op = OPERATIONS[name];
    if (!op) throw new Error("unknown Lamp operation " + name);
    const { status, text } = await this.send(this.request(op, input));
    let body = null;
    try { body = text ? JSON.parse(text) : null; } catch { body = { error: { code: "DATA_UNAVAILABLE", message: "invalid API JSON" } }; }
    if (status >= 400) throw new LampError(status, body);
    return body;
  }

  async waitOperation(operationId, timeoutMs = 60000) {
    const deadline = Date.now() + timeoutMs;
    for (;;) {
      const left = Math.max(0, Math.min(30000, deadline - Date.now()));
      const res = await this.call("operation_wait", { operation_id: operationId, timeout_ms: left });
      const op = res.data || res;
      if (!["accepted", "running"].includes(op.state) || Date.now() >= deadline) return op;
    }
  }
}'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    schema = json.loads((ROOT / 'contracts/public/schema.json').read_text())
    ops = operations(schema)
    lic = (ROOT / 'LICENSE').read_text()
    out = {**gen_typescript(schema, ops), 'sdk/typescript/LICENSE': lic}
    stale = []
    for rel, data in sorted(out.items()):
        p = ROOT / rel
        if args.check:
            if not p.exists() or p.read_text() != data:
                stale.append(rel)
        else:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(data)
    if stale:
        raise SystemExit('stale generated SDK file: ' + ', '.join(stale))
    print(f'sdk codegen: {"clean" if args.check else "generated"} ({len(ops)} operations)')


if __name__ == '__main__':
    main()
