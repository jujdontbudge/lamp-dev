#!/usr/bin/env python3
"""Writes the engine-gate template definition (lamp.template/v1).

The template installs the exact frozen benchmarks/workload.py as
/opt/lamp/bench-workload.py and checks its SHA-256 inside the guest, so the
harness's guest-workload digest check (benchmarks/engine.py) is satisfied by
the built template itself, never by a step in the timed path.

Usage: images/templates/make-bench.py SEED_REF [NAME MEMORY_MIB] > bench.lamp

NAME/MEMORY_MIB write the same workload at another guest size (E04 uses
`e04 512`: the storage oracle's pattern is 8 KiB of RAM, and a 4 GiB guest
would pin 4 GiB of host RAM per capture image).
"""
import base64
import hashlib
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
workload = (ROOT / "benchmarks" / "workload.py").read_bytes()
digest = hashlib.sha256(workload).hexdigest()
encoded = base64.b64encode(workload).decode()
seed_ref = sys.argv[1]
name = sys.argv[2] if len(sys.argv) > 2 else "bench"
memory = "\nmemory_mib = %d" % int(sys.argv[3]) if len(sys.argv) > 3 else ""
install = (
    "import base64,hashlib,os;"
    "os.makedirs('/opt/lamp',exist_ok=True);"
    f"data=base64.b64decode('{encoded}');"
    f"assert hashlib.sha256(data).hexdigest()=='{digest}';"
    "open('/opt/lamp/bench-workload.py','wb').write(data);"
    "os.chmod('/opt/lamp/bench-workload.py',0o644)"
)
print(f'''# Engine gate template (T6). Generated by images/templates/make-bench.py.
# workload sha256 {digest}
format = "lamp.template/v1"
name = "{name}"
guest_os = "linux"
arch = "x86_64"
seed_ref = {json.dumps(seed_ref)}
network = "none"{memory}

[[steps]]
argv = ["python3", "-c", {json.dumps(install)}]

[[steps]]
argv = ["sh", "-c", "python3 /opt/lamp/bench-workload.py identity > /opt/lamp/bench-identity.json && cc --version > /dev/null"]
''')
